  /**
   * Generates a Postman Collection v2.1.0 JSON for all discovered endpoints
   */
  public static exportPostman(analysis: AnalysisResult): object {
    const items = analysis.endpoints.map(endpoint => {
      const urlParts = endpoint.url.replace(/^https?:\/\//, '').split('/');
      const host = urlParts[0];
      const pathParts = urlParts.slice(1);

      const headers = Object.entries(endpoint.headers || {}).map(([key, value]) => ({
        key,
        value,
        type: 'text',
      }));

      // Add common authorization and signature headers if required
      if (endpoint.requiresSignature && !headers.some(h => h.key === 'X-Signature')) {
        headers.push({ key: 'X-Signature', value: '{{calculated_hmac_sha256}}', type: 'text' });
        headers.push({ key: 'X-Timestamp', value: '{{$timestamp}}', type: 'text' });
      }

      let requestBody: any = undefined;
      if (endpoint.method !== 'GET' && endpoint.samplePayload) {
        requestBody = {
          mode: 'raw',
          raw: typeof endpoint.samplePayload === 'string'
            ? endpoint.samplePayload
            : JSON.stringify(endpoint.samplePayload, null, 2),
          options: {
            raw: {
              language: 'json',
            },
          },
        };
      }

      return {
        name: `${endpoint.method} ${endpoint.path}`,
        request: {
          method: endpoint.method,
          header: headers,
          body: requestBody,
          url: {
            raw: endpoint.url,
            protocol: endpoint.url.startsWith('https') ? 'https' : 'http',
            host: [host],
            path: pathParts,
          },
          description: `Discovered from DEX bytecode.\nCategory: ${endpoint.category}\nAuth: ${endpoint.authType}\nSignature Required: ${endpoint.requiresSignature}`,
        },
      };
    });

    return {
      info: {
        _postman_id: `apkflow_${analysis.id}`,
        name: `ApkFlow - ${analysis.app.name} (${analysis.app.packageName})`,
        description: `Automated Postman Collection reconstructed from Android bytecode analysis.\nTotal Endpoints: ${analysis.endpoints.length}`,
        schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
      },
      item: items,
    };
  }

  /**
   * Generates OpenAPI 3.0.3 specification JSON
   */
  public static exportOpenApi(analysis: AnalysisResult): object {
    const paths: Record<string, any> = {};
    const baseDomain = analysis.endpoints[0]?.domain || 'api.example.com';

    for (const ep of analysis.endpoints) {
      if (!paths[ep.path]) {
        paths[ep.path] = {};
      }

      const methodLower = ep.method.toLowerCase();
      paths[ep.path][methodLower] = {
        summary: `${ep.method} ${ep.path}`,
        description: `Category: ${ep.category} | Source: ${ep.sourceContext}`,
        tags: [ep.category.toUpperCase()],
        parameters: Object.keys(ep.headers || {}).map(h => ({
          name: h,
          in: 'header',
          required: false,
          schema: { type: 'string' },
        })),
        responses: {
          '200': {
            description: 'Successful Response',
            content: {
              'application/json': {
                schema: {
                  type: 'object',
                  example: ep.sampleResponse || { status: 'success' },
                },
              },
            },
          },
        },
      };

      if (['post', 'put', 'patch'].includes(methodLower) && ep.samplePayload) {
        paths[ep.path][methodLower].requestBody = {
          required: true,
          content: {
            'application/json': {
              schema: {
                type: 'object',
                example: ep.samplePayload,
              },
            },
          },
        };
      }
    }

    return {
      openapi: '3.0.3',
      info: {
        title: `${analysis.app.name} API`,
        version: analysis.app.versionName || '1.0.0',
        description: `Reconstructed REST API specification generated by ApkFlow from Android DEX bytecode.`,
      },
      servers: [
        {
          url: `https://${baseDomain}`,
          description: 'Production Host',
        },
        {
          url: 'http://localhost:3840/api/mock',
          description: 'ApkFlow Virtual Mock Gateway',
        },
      ],
      paths,
    };
  }

